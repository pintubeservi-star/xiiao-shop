create or replace function public.cg_market_is_owner(p_merchant_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.cg_market_merchants m
    where m.id = p_merchant_id and m.owner_user_id = auth.uid()
  );
$$;
revoke all on function public.cg_market_is_owner(uuid) from public, anon;
grant execute on function public.cg_market_is_owner(uuid) to authenticated;

