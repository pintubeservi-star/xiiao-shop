create or replace function public.cg_market_create_order(
  p_merchant_id uuid,
  p_items jsonb,
  p_customer_name text,
  p_customer_phone text,
  p_delivery_mode text,
  p_address text,
  p_lat double precision,
  p_lng double precision,
  p_payment_method text,
  p_notes text default null,
  p_source text default 'marketplace',
  p_discount_dop numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_merchant public.cg_market_merchants%rowtype;
  v_product public.cg_market_products%rowtype;
  v_item jsonb;
  v_order public.cg_market_orders%rowtype;
  v_qty integer;
  v_line numeric(12,2);
  v_subtotal numeric(12,2) := 0;
  v_delivery numeric(12,2) := 0;
  v_commission numeric(12,2) := 0;
  v_invoice bigint;
  v_quote jsonb;
begin
  if v_user is null then raise exception 'Debes iniciar sesión para continuar.'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 40 then
    raise exception 'El carrito no es válido.';
  end if;
  select * into v_merchant from public.cg_market_merchants where id = p_merchant_id and status = 'approved' for share;
  if not found then raise exception 'Este comercio no está disponible.'; end if;
  if p_source not in ('marketplace','pos') then raise exception 'Origen de venta no válido.'; end if;
  if p_source = 'pos' and v_merchant.owner_user_id <> v_user then raise exception 'No autorizado para registrar ventas en este comercio.'; end if;
  if p_source = 'marketplace' and p_delivery_mode not in ('delivery','pickup') then raise exception 'Selecciona entrega o recogida.'; end if;
  if p_source='marketplace' and p_delivery_mode='delivery' and not v_merchant.delivery_enabled then raise exception 'Este comercio no tiene delivery habilitado.'; end if;
  if p_source='marketplace' and coalesce(p_discount_dop,0) <> 0 then raise exception 'Los descuentos del marketplace deben ser autorizados por el comercio.'; end if;
  if p_source = 'pos' and p_delivery_mode <> 'pickup' then raise exception 'Una venta de mostrador no puede solicitar delivery.'; end if;
  if p_payment_method not in ('cash','transfer') then raise exception 'Método de pago no válido.'; end if;
  if coalesce(p_discount_dop,0) < 0 then raise exception 'Descuento no válido.'; end if;
  if p_source = 'marketplace' and (nullif(trim(p_customer_name),'') is null or nullif(trim(p_customer_phone),'') is null) then
    raise exception 'Completa tu nombre y teléfono.';
  end if;
  if p_source = 'marketplace' and p_delivery_mode = 'delivery' then
    if v_merchant.pickup_lat is null or v_merchant.pickup_lng is null or p_lat is null or p_lng is null or nullif(trim(p_address),'') is null then
      raise exception 'El comercio o la dirección de entrega no tienen ubicación confirmada.';
    end if;
    if p_lat < 18.5 or p_lat > 19.5 or p_lng < -70.8 or p_lng > -69.5 then raise exception 'Por ahora el delivery está disponible dentro de la zona de Cotuí.'; end if;
    v_quote := public.cg_quote_fare('package',v_merchant.pickup_lat,v_merchant.pickup_lng,p_lat,p_lng);
    v_delivery := coalesce((v_quote->>'fare_dop')::numeric,0);
  end if;

  insert into public.cg_market_orders(
    merchant_id,customer_user_id,created_by,source,status,payment_method,payment_status,delivery_mode,
    customer_name,customer_phone,delivery_address,customer_lat,customer_lng,notes,discount_dop
  ) values (
    p_merchant_id,case when p_source='marketplace' then v_user else null end,v_user,p_source,
    case when p_source='pos' then 'completed' else 'new' end,p_payment_method,
    case when p_source='pos' then 'paid' else 'pending' end,
    case when p_source='pos' then 'pickup' else p_delivery_mode end,
    coalesce(nullif(trim(p_customer_name),''),'Venta de mostrador'),
    coalesce(nullif(trim(p_customer_phone),''),v_merchant.phone),
    nullif(trim(p_address),''),p_lat,p_lng,nullif(trim(p_notes),''),coalesce(p_discount_dop,0)
  ) returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce((v_item->>'product_id'),'') = '' then raise exception 'Hay un producto inválido en el carrito.'; end if;
    v_qty := coalesce((v_item->>'quantity')::integer,0);
    if v_qty < 1 or v_qty > 99 then raise exception 'Cantidad no válida.'; end if;
    select * into v_product from public.cg_market_products
      where id = (v_item->>'product_id')::uuid and merchant_id = p_merchant_id and status = 'active'
      for update;
    if not found then raise exception 'Uno de los productos ya no está disponible.'; end if;
    if v_product.track_stock and v_product.stock < v_qty then raise exception 'Inventario insuficiente para: %',v_product.name; end if;
    v_line := round(v_product.price_dop * v_qty,2);
    v_subtotal := v_subtotal + v_line;
    if v_product.track_stock then
      update public.cg_market_products set stock = stock - v_qty, updated_at = now() where id = v_product.id;
      insert into public.cg_market_inventory_movements(merchant_id,product_id,order_id,movement_type,quantity_delta,note,created_by)
      values(p_merchant_id,v_product.id,v_order.id,case when p_source='pos' then 'pos_sale' else 'sale' end,-v_qty,
        case when p_source='pos' then 'Venta en punto de venta' else 'Pedido marketplace #'||v_order.order_number end,v_user);
    end if;
    insert into public.cg_market_order_items(order_id,product_id,product_name,product_sku,quantity,unit_price_dop,line_total_dop)
    values(v_order.id,v_product.id,v_product.name,v_product.sku,v_qty,v_product.price_dop,v_line);
  end loop;

  if coalesce(p_discount_dop,0) > v_subtotal then raise exception 'El descuento supera el subtotal.'; end if;
  if p_source = 'marketplace' then
    v_commission := round((v_subtotal - coalesce(p_discount_dop,0)) * v_merchant.commission_pct / 100,2);
  end if;

  update public.cg_market_orders set
    subtotal_dop = v_subtotal,
    delivery_fee_dop = v_delivery,
    total_dop = v_subtotal - coalesce(p_discount_dop,0) + v_delivery,
    marketplace_commission_pct = case when p_source='marketplace' then v_merchant.commission_pct else 0 end,
    marketplace_commission_dop = v_commission,
    delivery_payment_status = case when p_delivery_mode='pickup' or p_source='pos' then 'not_applicable' else 'pending' end,
    updated_at = now()
  where id = v_order.id returning * into v_order;

  insert into public.cg_market_invoices(merchant_id,order_id,merchant_snapshot,customer_snapshot,totals_snapshot)
  values(
    p_merchant_id,v_order.id,
    jsonb_build_object('store_name',v_merchant.store_name,'legal_name',v_merchant.legal_name,'rnc',v_merchant.rnc,'address',v_merchant.address,'phone',v_merchant.phone),
    jsonb_build_object('name',v_order.customer_name,'phone',v_order.customer_phone,'address',v_order.delivery_address),
    jsonb_build_object('subtotal_dop',v_order.subtotal_dop,'discount_dop',v_order.discount_dop,'delivery_fee_dop',v_order.delivery_fee_dop,'total_dop',v_order.total_dop,'currency','DOP','fiscal_notice','Recibo interno; no sustituye un comprobante fiscal electrónico e-CF')
  ) returning invoice_number into v_invoice;

  return jsonb_build_object(
    'order_id',v_order.id,'order_number',v_order.order_number,'invoice_number',v_invoice,
    'subtotal_dop',v_order.subtotal_dop,'delivery_fee_dop',v_order.delivery_fee_dop,
    'total_dop',v_order.total_dop,'marketplace_commission_dop',v_order.marketplace_commission_dop,
    'payment_status',v_order.payment_status,'status',v_order.status
  );
end;
$$;
revoke all on function public.cg_market_create_order(uuid,jsonb,text,text,text,text,double precision,double precision,text,text,text,numeric) from public, anon;
grant execute on function public.cg_market_create_order(uuid,jsonb,text,text,text,text,double precision,double precision,text,text,text,numeric) to authenticated;

create or replace function public.cg_market_update_order(
  p_order_id uuid,
  p_status text default null,
  p_payment_status text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare v_order public.cg_market_orders%rowtype; v_item record;
begin
  select * into v_order from public.cg_market_orders where id=p_order_id for update;
  if not found or (v_order.merchant_id is null) or not public.cg_market_is_owner(v_order.merchant_id) then
    raise exception 'Pedido no encontrado o no autorizado.';
  end if;
  if p_status is not null then
    if p_status not in ('accepted','preparing','ready_for_pickup','completed','rejected','cancelled') then raise exception 'Estado no permitido.'; end if;
    if p_status='completed' and v_order.delivery_mode <> 'pickup' then raise exception 'El repartidor debe confirmar la entrega de este pedido.'; end if;
    if p_status in ('rejected','cancelled') and v_order.delivery_request_id is not null then raise exception 'Este pedido ya fue enviado a delivery. Contacta administración para cancelarlo.'; end if;
    if p_status in ('rejected','cancelled') and v_order.status not in ('new','accepted','preparing','ready_for_pickup') then raise exception 'No se puede cancelar en este estado.';
    end if;
    if p_status in ('rejected','cancelled') and v_order.status not in ('rejected','cancelled') then
      for v_item in select product_id,quantity from public.cg_market_order_items where order_id=p_order_id and product_id is not null
      loop
        update public.cg_market_products set stock=stock+v_item.quantity,updated_at=now() where id=v_item.product_id and track_stock;
        insert into public.cg_market_inventory_movements(merchant_id,product_id,order_id,movement_type,quantity_delta,note,created_by)
        values(v_order.merchant_id,v_item.product_id,p_order_id,'cancellation_return',v_item.quantity,'Devolución por cancelación',auth.uid());
      end loop;
    end if;
    update public.cg_market_orders set status=p_status,cancelled_at=case when p_status in ('rejected','cancelled') then now() else cancelled_at end,updated_at=now() where id=p_order_id;
  end if;
  if p_payment_status is not null then
    if p_payment_status not in ('pending','paid','failed','refunded') then raise exception 'Estado de pago no permitido.'; end if;
    update public.cg_market_orders set payment_status=p_payment_status,updated_at=now() where id=p_order_id;
  end if;
end;
$$;
revoke all on function public.cg_market_update_order(uuid,text,text) from public, anon;
grant execute on function public.cg_market_update_order(uuid,text,text) to authenticated;

create or replace function public.cg_market_dispatch_order(p_order_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.cg_market_orders%rowtype;
  v_merchant public.cg_market_merchants%rowtype;
  v_category public.cg_market_categories%rowtype;
  v_delivery public.cg_delivery_requests%rowtype;
begin
  select * into v_order from public.cg_market_orders where id=p_order_id for update;
  if not found or not public.cg_market_is_owner(v_order.merchant_id) then raise exception 'Pedido no encontrado o no autorizado.'; end if;
  if v_order.source <> 'marketplace' or v_order.delivery_mode <> 'delivery' then raise exception 'Este pedido no requiere repartidor.'; end if;
  if v_order.status <> 'ready_for_pickup' then raise exception 'Primero marca el pedido como listo para recoger.'; end if;
  if v_order.delivery_request_id is not null then raise exception 'Este pedido ya tiene un repartidor solicitado.'; end if;
  select * into v_merchant from public.cg_market_merchants where id=v_order.merchant_id;
  select * into v_category from public.cg_market_categories where id=v_merchant.category_id;
  if not v_merchant.delivery_enabled then raise exception 'Este comercio no tiene delivery habilitado.'; end if;
  if v_merchant.pickup_lat is null or v_merchant.pickup_lng is null or v_order.customer_lat is null or v_order.customer_lng is null then
    raise exception 'Falta la ubicación GPS del comercio o del cliente.';
  end if;
  insert into public.cg_delivery_requests(
    customer_id,sender_name,sender_phone,recipient_name,recipient_phone,pickup_address,delivery_address,
    package_type,package_description,status,pickup_lat,pickup_lng,destination_lat,destination_lng,
    distance_km,service_kind
  ) values (
    v_order.customer_user_id,v_merchant.store_name,v_merchant.phone,v_order.customer_name,v_order.customer_phone,
    v_merchant.address,v_order.delivery_address,
    case when v_category.slug='restaurantes' or v_category.slug='reposteria' then 'comida' else 'compra' end,
    'Pedido Cotuí Go Market #'||v_order.order_number,'requested',
    v_merchant.pickup_lat,v_merchant.pickup_lng,v_order.customer_lat,v_order.customer_lng,
    null,case when v_category.slug='restaurantes' or v_category.slug='reposteria' then 'food' else 'package' end
  ) returning * into v_delivery;
  update public.cg_market_orders set delivery_request_id=v_delivery.id,delivery_tracking_token=v_delivery.tracking_token,delivery_tracking_code=v_delivery.tracking_code,status='courier_requested',delivery_fee_dop=coalesce(v_delivery.estimated_fee_dop,delivery_fee_dop),total_dop=subtotal_dop-discount_dop+coalesce(v_delivery.estimated_fee_dop,delivery_fee_dop),updated_at=now() where id=v_order.id;
  return jsonb_build_object('delivery_id',v_delivery.id,'tracking_token',v_delivery.tracking_token,'tracking_code',v_delivery.tracking_code,'status',v_delivery.status);
end;
$$;
revoke all on function public.cg_market_dispatch_order(uuid) from public, anon;
grant execute on function public.cg_market_dispatch_order(uuid) to authenticated;

create or replace function public.cg_market_sync_delivery_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.cg_market_orders
  set status = case
    when new.status='accepted' then 'courier_assigned'
    when new.status='picked_up' then 'picked_up'
    when new.status='on_the_way' then 'on_the_way'
    when new.status='delivered' then 'delivered'
    when new.status='cancelled' then 'ready_for_pickup'
    else status end,
    delivery_request_id = case when new.status='cancelled' then null else delivery_request_id end,
    updated_at=now()
  where delivery_request_id=new.id;
  return new;
end;
$$;
revoke all on function public.cg_market_sync_delivery_status() from public, anon, authenticated;
drop trigger if exists cg_market_sync_delivery_status_trigger on public.cg_delivery_requests;
create trigger cg_market_sync_delivery_status_trigger
after update of status on public.cg_delivery_requests
for each row when (old.status is distinct from new.status)
execute function public.cg_market_sync_delivery_status();

create or replace function public.cg_market_adjust_stock(p_product_id uuid,p_delta integer,p_note text default null)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare v_product public.cg_market_products%rowtype; v_stock integer;
begin
  if p_delta=0 or abs(p_delta)>100000 then raise exception 'Cantidad de ajuste no válida.'; end if;
  select * into v_product from public.cg_market_products where id=p_product_id for update;
  if not found or not public.cg_market_is_owner(v_product.merchant_id) then raise exception 'Producto no encontrado o no autorizado.'; end if;
  if not v_product.track_stock then raise exception 'Este producto no controla inventario.'; end if;
  if v_product.stock+p_delta<0 then raise exception 'El inventario no puede quedar negativo.'; end if;
  update public.cg_market_products set stock=stock+p_delta,updated_at=now() where id=p_product_id returning stock into v_stock;
  insert into public.cg_market_inventory_movements(merchant_id,product_id,movement_type,quantity_delta,note,created_by)
  values(v_product.merchant_id,p_product_id,case when p_delta>0 then 'restock' else 'adjustment' end,p_delta,coalesce(p_note,'Ajuste manual'),auth.uid());
  return v_stock;
end;
$$;
revoke all on function public.cg_market_adjust_stock(uuid,integer,text) from public, anon;
grant execute on function public.cg_market_adjust_stock(uuid,integer,text) to authenticated;

create or replace function public.cg_market_admin_set_merchant_status(
  p_merchant_id uuid,p_status text,p_plan text default null,p_commission_pct numeric default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.cg_is_admin() then raise exception 'No autorizado.'; end if;
  if p_status not in ('pending','approved','suspended','rejected') then raise exception 'Estado no válido.'; end if;
  if p_plan is not null and p_plan not in ('free','business','premium') then raise exception 'Plan no válido.'; end if;
  if p_commission_pct is not null and (p_commission_pct<0 or p_commission_pct>20) then raise exception 'Comisión no válida.'; end if;
  update public.cg_market_merchants set
    status=p_status,
    plan=coalesce(p_plan,plan),
    commission_pct=coalesce(p_commission_pct,case when p_plan='business' then 3 when p_plan='premium' then 2 when p_plan='free' then 5 else commission_pct end),
    updated_at=now()
  where id=p_merchant_id;
  if not found then raise exception 'Comercio no encontrado.'; end if;
end;
$$;
revoke all on function public.cg_market_admin_set_merchant_status(uuid,text,text,numeric) from public, anon;
grant execute on function public.cg_market_admin_set_merchant_status(uuid,text,text,numeric) to authenticated;

