create table if not exists public.cg_market_merchants (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null unique references auth.users(id) on delete cascade,
  category_id uuid references public.cg_market_categories(id) on delete set null,
  store_name text not null,
  slug text not null unique,
  description text,
  phone text not null,
  whatsapp text,
  address text not null,
  pickup_lat double precision,
  pickup_lng double precision,
  logo_url text,
  cover_url text,
  payment_instructions text,
  legal_name text,
  rnc text,
  status text not null default 'pending' check (status in ('pending','approved','suspended','rejected')),
  plan text not null default 'free' check (plan in ('free','business','premium')),
  commission_pct numeric(5,2) not null default 5 check (commission_pct between 0 and 20),
  delivery_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cg_market_products (
  id uuid primary key default gen_random_uuid(),
  merchant_id uuid not null references public.cg_market_merchants(id) on delete cascade,
  category_id uuid references public.cg_market_categories(id) on delete set null,
  name text not null,
  description text,
  sku text,
  price_dop numeric(12,2) not null check (price_dop >= 0),
  compare_at_price_dop numeric(12,2) check (compare_at_price_dop is null or compare_at_price_dop >= price_dop),
  stock integer not null default 0 check (stock >= 0),
  track_stock boolean not null default true,
  unit text not null default 'unidad',
  image_url text,
  images text[] not null default '{}',
  status text not null default 'draft' check (status in ('draft','active','paused','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cg_market_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  merchant_id uuid not null references public.cg_market_merchants(id),
  customer_user_id uuid references auth.users(id) on delete set null,
