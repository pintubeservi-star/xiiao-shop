  payment_method text not null check (payment_method in ('cash','transfer','card')),
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','failed','refunded')),
  delivery_payment_status text not null default 'pending' check (delivery_payment_status in ('pending','paid','not_applicable')),
  delivery_mode text not null default 'delivery' check (delivery_mode in ('delivery','pickup')),
  customer_name text not null,
  customer_phone text not null,
  delivery_address text,
  customer_lat double precision,
  customer_lng double precision,
  notes text,
  subtotal_dop numeric(12,2) not null default 0 check (subtotal_dop >= 0),
  discount_dop numeric(12,2) not null default 0 check (discount_dop >= 0),
  delivery_fee_dop numeric(12,2) not null default 0 check (delivery_fee_dop >= 0),
  total_dop numeric(12,2) not null default 0 check (total_dop >= 0),
  marketplace_commission_pct numeric(5,2) not null default 0,
  marketplace_commission_dop numeric(12,2) not null default 0,
  platform_fee_status text not null default 'pending' check (platform_fee_status in ('pending','paid','waived')),
  delivery_request_id uuid references public.cg_delivery_requests(id) on delete set null,
  delivery_tracking_token text,
  delivery_tracking_code text,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cg_market_order_items (
